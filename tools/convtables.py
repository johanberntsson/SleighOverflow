#!/usr/bin/env python3
"""The four easing curves as tables, so the MEGA65 needs no floating point.

    python3 tools/convtables.py <build dir>

writes <build>/tables.c and <build>/tables.h.

stranded.c uses its easing functions in exactly four places, each with a
fixed input -- a frame counter over a fixed length -- and each turned into a
whole pixel position at once:

    face y    (int)( 240 - 155 * ease_out_elastic( m / 120 )
                         - 15 * ease_in_out_quad( m / 120 ) )   m = 0..120
    logo y    (int)( -200 + 210 * ease_out_bounce( m / 60 ) )   m = 0..60
    credits x (int)( -160 + 320 * ease_out_quad( m / 60 ) )     m = 0..60
    boat x    (int)( -320 + 130 * ease_out_quad( m / 120 ) )    m = 0..

so each is a table of the integers it produces, computed here with the
original's own formulas in 32-bit floats. The boat's counter is not stopped
at 120 -- it runs until the fade to black ends, past the top of the curve,
and the boat drifts back -- so its table is longer than the others, and the
game holds the last entry if it ever gets there.
"""

import math
import os
import sys

import numpy as np

f = np.float32


def ease_in_out_quad(t):
    t = f(t) * f(2)
    if t < f(1):
        return f(0.5) * t * t
    return f(-0.5) * ((t - f(1)) * (t - f(3)) - f(1))


def ease_out_quad(t):
    t = f(t)
    return -t * (t - f(2))


def ease_out_elastic(t):
    t = f(t)
    if t == f(0):
        return f(0)
    if t == f(1):
        return f(1)
    p = f(0.4)
    s = p / f(4)
    return (f(math.pow(2.0, float(f(-10) * t)))
            * f(math.sin(float((t - s) * (f(2) * f(math.acos(-1.0))) / p)))
            + f(1))


def ease_out_bounce(t):
    t = f(t)
    if t < f(1) / f(2.75):
        return f(7.5625) * t * t
    if t < f(2) / f(2.75):
        t = t - f(1.5) / f(2.75)
        return f(7.5625) * t * t + f(0.75)
    if t < f(2.5) / f(2.75):
        t = t - f(2.25) / f(2.75)
        return f(7.5625) * t * t + f(0.9375)
    t = t - f(2.625) / f(2.75)
    return f(7.5625) * t * t + f(0.984375)


def trunc(v):
    return int(math.trunc(float(v)))  # C's (int) of a float


BOAT_FRAMES = 256

TABLES = {
    "ease_face_y": [trunc(f(240) - f(155) * ease_out_elastic(f(m) / f(120))
                          - f(15) * ease_in_out_quad(f(m) / f(120)))
                    for m in range(121)],
    "ease_logo_y": [trunc(f(-200) + f(210) * ease_out_bounce(f(m) / f(60)))
                    for m in range(61)],
    "ease_credits_x": [trunc(f(-160) + f(320) * ease_out_quad(f(m) / f(60)))
                       for m in range(61)],
    "ease_boat_x": [trunc(f(-320) + f(130) * ease_out_quad(f(m) / f(120)))
                    for m in range(BOAT_FRAMES)],
}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build = sys.argv[1]
    with open(os.path.join(build, "tables.h"), "w") as h:
        h.write("// Generated by tools/convtables.py. Do not edit.\n")
        h.write("#ifndef TABLES_H\n#define TABLES_H\n\n#include <stdint.h>\n\n")
        for name, vals in TABLES.items():
            h.write(f"#define {name.upper()}_LEN {len(vals)}\n")
            h.write(f"extern const int16_t {name}[{len(vals)}];\n")
        h.write("\n#endif\n")
    with open(os.path.join(build, "tables.c"), "w") as c:
        c.write("// Generated by tools/convtables.py. Do not edit.\n")
        c.write('#include "tables.h"\n')
        for name, vals in TABLES.items():
            c.write(f"\nconst int16_t {name}[{len(vals)}] = {{\n")
            for i in range(0, len(vals), 12):
                c.write("  " + ", ".join(str(v) for v in vals[i:i + 12])
                        + ",\n")
            c.write("};\n")


if __name__ == "__main__":
    main()
